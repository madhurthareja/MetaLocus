"""Locus dashboard: replays a full processed sequence (every frame, real
SAM 3.1 masks, real persistent memory graph state, real TTC, real spoken
directives) generated by scripts/generate_dashboard_data.py.

Deliberately a replay, not a live camera feed -- same reasoning as
PROJECT_PLAN.md's demo section: deterministic, no live-camera risk, while
still showing the full real pipeline end to end.

Run: python dashboard/app.py
"""

from __future__ import annotations

import gzip
import json
from pathlib import Path

from flask import Flask, jsonify, render_template, request, send_from_directory

DATA_DIR = Path(__file__).parent / "data"

app = Flask(__name__)
app.config["TEMPLATES_AUTO_RELOAD"] = True

_COMPRESSIBLE_MIMETYPES = {"application/json", "text/html", "text/css", "application/javascript"}


@app.after_request
def _compress(response):
    # A session's timeline.json runs ~7MB of repetitive numeric data --
    # gzip takes that under 1MB. Only text/JSON responses benefit (the
    # frame/mask video and audio files are already compressed); images
    # would just waste CPU re-compressing incompressible bytes.
    if (
        response.mimetype not in _COMPRESSIBLE_MIMETYPES
        or "gzip" not in request.headers.get("Accept-Encoding", "")
        or response.direct_passthrough
        or len(response.get_data()) < 1024
    ):
        return response
    response.set_data(gzip.compress(response.get_data(), compresslevel=6))
    response.headers["Content-Encoding"] = "gzip"
    response.headers["Content-Length"] = len(response.get_data())
    response.vary.add("Accept-Encoding")
    return response


def _sessions() -> list[str]:
    if not DATA_DIR.exists():
        return []
    return sorted(
        p.name for p in DATA_DIR.iterdir() if p.is_dir() and (p / "timeline.json").exists()
    )


@app.route("/")
def index():
    return render_template("index.html", sessions=_sessions())


@app.route("/api/sessions")
def api_sessions():
    return jsonify(_sessions())


@app.route("/api/timeline/<session>")
def api_timeline(session: str):
    path = DATA_DIR / session / "timeline.json"
    if not path.exists():
        return jsonify({"error": f"no such session: {session}"}), 404
    return json.loads(path.read_text())


@app.route("/data/<name>.json")
def data_root_json(name: str):
    # Dataset-level files (ablation/reproducibility/system-facts) living
    # directly under dashboard/data/, as opposed to a session's own
    # timeline.json under dashboard/data/<session>/ -- a distinct literal
    # ".json" suffix pattern so this never collides with the session route.
    path = DATA_DIR / f"{name}.json"
    if not path.exists():
        return jsonify({"error": f"no such data file: {name}.json"}), 404
    return send_from_directory(DATA_DIR, f"{name}.json")


@app.route("/data/<session>/<path:filename>")
def data_file(session: str, filename: str):
    return send_from_directory(DATA_DIR / session, filename)


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=5050, debug=False, threaded=True)
